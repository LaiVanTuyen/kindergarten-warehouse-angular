"""Subset the self-hosted Phosphor icon fonts + CSS to the icons the portal can use.

Run after adding new icons:  python tools/subset-phosphor.py
Writes libs/theme/phosphor.portal.css and libs/theme/fonts/Phosphor*.portal.woff2.

Icon names are sometimes built at runtime ('ph-' + icon), so we keep every icon
whose name appears ANYWHERE in portal/lib sources as a word — a safe superset.
"""
import pathlib, re
from fontTools import subset
from fontTools.ttLib import TTFont

ROOT = pathlib.Path(__file__).resolve().parents[1]
THEME = ROOT / "libs" / "theme"
CSS = (THEME / "phosphor.css").read_text(encoding="utf-8")
SOURCES = [ROOT / "apps" / "portal" / "src", ROOT / "libs"]
WEIGHTS = {"ph": "Phosphor", "ph-bold": "Phosphor-Bold", "ph-fill": "Phosphor-Fill"}

rule = re.compile(r'\.(ph(?:-bold|-fill)?)\.ph-([a-z0-9-]+):before\s*\{\s*content:\s*"\\([0-9a-f]+)";\s*\}', re.S)
glyphs = [(w, name, int(cp, 16)) for w, name, cp in rule.findall(CSS)]
all_names = {n for _, n, _ in glyphs}

words = set()
for base in SOURCES:
    for f in base.rglob("*"):
        if f.suffix in (".ts", ".html", ".scss", ".css") and "phosphor" not in f.name:
            words.update(re.findall(r"[a-z0-9]+(?:-[a-z0-9]+)*", f.read_text(encoding="utf-8", errors="ignore")))
used = {w[3:] if w.startswith("ph-") else w for w in words}
keep = sorted(all_names & used)
print(f"{len(keep)} of {len(all_names)} icon names kept")

out_css = ["/* GENERATED by tools/subset-phosphor.py from phosphor.css — do not edit. */"]
head = CSS.split("/* ===== Phosphor regular ===== */", 1)[1]
for weight, family in WEIGHTS.items():
    # Copy the @font-face + base class block for this weight, pointing at the subset file.
    block = re.search(r'@font-face\s*\{[^}]*font-family:\s*"%s"[^}]*\}\s*\.%s\s*\{[^}]*\}' % (family, re.escape(weight)), CSS).group(0)
    out_css.append(block.replace(f"/fonts/{family}.woff2", f"/fonts/{family}.portal.woff2"))
    cps = [cp for w, n, cp in glyphs if w == weight and n in keep]
    out_css += [f'.{weight}.ph-{n}:before {{ content: "\\{cp:x}"; }}' for w, n, cp in glyphs if w == weight and n in keep]
    font = TTFont(THEME / "fonts" / f"{family}.woff2")
    opts = subset.Options(); opts.flavor = "woff2"; opts.layout_features = []; opts.name_IDs = ["*"]
    s = subset.Subsetter(opts); s.populate(unicodes=cps); s.subset(font)
    dst = THEME / "fonts" / f"{family}.portal.woff2"
    font.flavor = "woff2"; font.save(dst)
    print(f"{family}: {(THEME / 'fonts' / (family + '.woff2')).stat().st_size // 1024} KB -> {dst.stat().st_size // 1024} KB")
(THEME / "phosphor.portal.css").write_text("\n".join(out_css) + "\n", encoding="utf-8")
print("css:", len(CSS) // 1024, "KB ->", (THEME / "phosphor.portal.css").stat().st_size // 1024, "KB")
